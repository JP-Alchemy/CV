// A d20, face on, showing `n`.
const D20 = [
  '.....#######.....',
  '...##.......##...',
  '.##...........##.',
  '#...............#',
  '#...............#',
  '#...............#',
  '#...............#',
  '#...............#',
  '#...............#',
  '#...............#',
  '#...............#',
  '.##...........##.',
  '...##.......##...',
  '.....#######.....',
];
export function d20(n) {
  const rows = D20.map((r) => [...r]);
  const t = typeset(String(n), { size: 1 });
  const ox = Math.floor((17 - t.width) / 2), oy = 4;
  for (let i = 0; i < t.blocks.length; i += 5) rows[oy + t.blocks[i + 1]][ox + t.blocks[i]] = '#';
  return rows.map((r) => r.join(''));
}

const TONE = { '#': 1, '+': 0.55, '-': 0.3 };

/** Sprite rows -> blocks (x, y, w, h, tone) of `cell` px; '*' takes `star` (a colour index, or ink). */
export function blocks(rows, cell, { star = null, tone = null } = {}) {
  const out = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      const c = r[x];
      let t;
      if (c === '.') continue;
      if (c === '*') { if (star === null) continue; t = star < 0 ? 1 : 2 + star; }
      else if (c >= '1' && c <= '7') t = 1 + Number(c);
      else t = TONE[c];
      out.push(x * cell, y * cell, cell, cell, tone ?? t);
    }
  });
  return Float32Array.from(out);
}

/** Frames of one sprite with equal block counts, so the engine can tumble between them. */
export function frames(list, cell, opts) {
  const fs = list.map((rows) => blocks(rows, cell, opts));
  const cap = Math.max(...fs.map((f) => f.length / 5));
  return fs.map((f) => {
    const n = f.length / 5, out = new Float32Array(cap * 5);
    for (let j = 0; j < cap; j++) out.set(f.subarray(Math.floor((j * n) / cap) * 5, Math.floor((j * n) / cap) * 5 + 5), j * 5);
    return out;
  });
}

export const size = (rows, cell) => ({ w: rows[0].length * cell, h: rows.length * cell });
