// Typographic stand-ins, drawn with the plain glyphs.
export const ALIAS = {
  '’': "'", '‘': "'", '“': '"', '”': '"', '−': '-', '…': '...',
};

/** Every character the font draws (scripts/font.mjs turns them into a font file). */
export const CHARS = Object.keys(RAW);

export const SPACE = 3; // width of a space in font pixels
export const CAP = 7; // cap height in font pixels

const glyphs = new Map();
for (const [ch, rows] of Object.entries(RAW)) {
  const w = rows.reduce((m, r) => Math.max(m, r.length), 0);
  const px = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] === '#') px.push(x, y);
  });
  glyphs.set(ch, { w, px: Int8Array.from(px) });
}

const boldCache = new Map();
function embolden(g) {
  // Fake bold: OR the glyph with itself shifted one pixel right.
  const seen = new Set();
  const out = [];
  for (let i = 0; i < g.px.length; i += 2) {
    for (const dx of [0, 1]) {
      const k = (g.px[i] + dx) * 16 + g.px[i + 1];
      if (!seen.has(k)) { seen.add(k); out.push(g.px[i] + dx, g.px[i + 1]); }
    }
  }
  return { w: g.w + 1, px: Int8Array.from(out) };
}

const fallback = glyphs.get('?');

export function glyph(ch, bold = false) {
  let g = glyphs.get(ch);
  if (!g) {
    const a = ALIAS[ch];
    if (a && a.length === 1) g = glyphs.get(a);
    else if (!g) {
      const up = ch.toUpperCase();
      g = glyphs.get(up) || glyphs.get(ch.normalize('NFD')[0]) || fallback;
    }
  }
  if (!bold) return g;
  let b = boldCache.get(g);
  if (!b) { b = embolden(g); boldCache.set(g, b); }
  return b;
}

/** Replace multi-glyph aliases ("…" -> "...") before layout. */
export function normalize(str) {
  return str.replace(/…/g, '...');
}
