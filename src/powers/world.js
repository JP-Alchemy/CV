export const LAND_COLS = 72, LAND_ROWS = 36;

/** 1 where a 5° cell is land: row 0 is 85-90°N, column 0 is 180-175°W. */
export const LAND = (() => {
  const m = new Uint8Array(LAND_COLS * LAND_ROWS);
  BANDS.forEach((runs, j) => {
    for (const [a, b] of runs) {
      for (let i = 0; i < LAND_COLS; i++) {
        const lon = -180 + i * 5 + 2.5;
        if (lon >= a && lon <= b) m[j * LAND_COLS + i] = 1;
      }
    }
  });
  return m;
})();

/** Is (lat, lon) in degrees land? */
export function land(lat, lon) {
  const j = Math.min(LAND_ROWS - 1, Math.max(0, Math.floor((90 - lat) / 5)));
  const i = (((Math.floor((lon + 180) / 5)) % LAND_COLS) + LAND_COLS) % LAND_COLS;
  return LAND[j * LAND_COLS + i] === 1;
}
