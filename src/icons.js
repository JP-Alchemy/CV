/**
 * Build equal-length block frames for an icon so frame k -> k+1 maps 1:1.
 * Frames with fewer squares duplicate some (overlapping squares are invisible).
 */
export function iconFrames(name, cell, tone = 1) {
  const src = ICONS[name];
  const raw = src.map((rows) => {
    const pts = [];
    rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') pts.push([x, y]); });
    return pts;
  });
  const cap = Math.max(...raw.map((p) => p.length));
  const frames = raw.map((pts) => {
    const out = new Float32Array(cap * 5);
    for (let j = 0; j < cap; j++) {
      const [x, y] = pts[Math.floor((j * pts.length) / cap)];
      out.set([x * cell, y * cell, cell, cell, tone], j * 5);
    }
    return out;
  });
  const cols = Math.max(...src[0].map((r) => r.length));
  return { frames, w: cols * cell, h: src[0].length * cell };
}
